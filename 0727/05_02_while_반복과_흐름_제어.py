print("========== 1. while 문의 기본 구조 ==========")

# ---------------------------------------------------------------------------
# 형식:
#     while 조건식:            ← 조건이 '참인 동안' 계속 반복
#         반복할 코드
#
# for 는 횟수를 정해 놓고 돌지만, while 은 조건이 거짓이 될 때까지 돈다.
# ---------------------------------------------------------------------------

count = 1                         # ① 시작 상태
while count <= 3:                 # ② 종료 조건 (거짓이 되면 멈춤)
    print(count)                  # → 1 2 3
    count = count + 1             # ③ 갱신 (거짓 방향으로!)

# 추적: count=1 참→출력1,2로  /  2 참→출력2,3으로  /  3 참→출력3,4로  /  4 거짓→종료


print()
print("========== 2. ★가장 중요★ 무한 루프 예방 3점검 ==========")

# ---------------------------------------------------------------------------
# while 은 멈추는 법을 '직접 설계'해야 한다. 세 가지를 점검:
#
#   점검 항목     확인할 것                       빠뜨리면
#   ① 시작값     조건 변수가 반복 전에 정해졌나      오작동
#   ② 종료 조건   언젠가 반드시 거짓이 되나         무한 루프
#   ③ 갱신       거짓 방향으로 값이 바뀌나         무한 루프
#
# 아래는 갱신이 빠진 무한 루프 예시 (절대 주석을 풀지 말 것! 풀었다면 Ctrl+C 로 강제 중단)
#
#   count = 1
#   while count <= 3:
#       print(count)          # count 가 영원히 1 → 1을 무한 출력!
#       # count += 1          ← 이 줄이 없으면 안 멈춘다
# ---------------------------------------------------------------------------

count = 1
while count <= 3:
    print(count)                  # → 1 2 3
    count += 1                    # 갱신이 있어야 멈춘다


