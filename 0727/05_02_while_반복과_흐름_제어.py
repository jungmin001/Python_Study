print("========== 9. 최댓값·최솟값 찾기 ― 갱신 패턴 ==========")

# ---------------------------------------------------------------------------
# ① 첫 값을 기준으로 삼고  ② 더 크면(작으면) 그때마다 갱신
# 04_01 의 sort() 없이도 찾을 수 있는, 반복문의 대표 패턴이다.
# ---------------------------------------------------------------------------

values = [77, 92, 68, 85, 74]

max_value = values[0]             # 첫 값(77)을 기준으로
min_value = values[0]
for v in values:
    if v > max_value:
        max_value = v             # 더 큰 값을 만나면 교체
    if v < min_value:
        min_value = v             # 더 작은 값을 만나면 교체
print("최대:", max_value, "최소:", min_value)     # → 최대: 92 최소: 68


