print("========== 10. 플래그 변수 ― 있었는지 기억하기 ==========")

# ---------------------------------------------------------------------------
# 플래그(flag) = 어떤 일이 '일어났는지'를 기억하는 True/False 변수.
#   ① False 로 시작  ② 조건을 만나면 True 로  ③ 반복 뒤 플래그로 판단
# break 와 함께 쓰면 "하나라도 찾으면 바로 그만" 검색이 된다.
# ---------------------------------------------------------------------------

found = False                     # 아직 못 찾음
for v in [70, 92, 65]:            # 측정값들
    if v > 80:
        found = True              # 찾았다고 표시
        break                     # 더 볼 필요 없으니 중단

if found:
    print("이상값 있음")            # → 이상값 있음   (92 때문)
else:
    print("모두 정상")


print()
print("========== 11. 문제 해결 4단계 ==========")

# ---------------------------------------------------------------------------
# 막막한 문제는 네 부분으로 분해한다:
#
#   ① 입력  : 필요한 값 받고 변수 초기화     (total = 0, found = False ...)
#   ② 반복  : 여러 값 처리                  (for 또는 while)
#   ③ 판단  : 각 값을 조건으로 처리          (if)
#   ④ 출력  : 결과 정리해 보여주기           (print, f-string)
# ---------------------------------------------------------------------------

# 종합 미니 프로그램: 평균 + 초과 개수 + 이상 여부를 한 반복에서
values = [75, 88, 79, 91, 62]     # ← input 대신 준비된 측정값 (①)

total = 0
over = 0
found = False
for v in values:                  # ② 반복
    total += v
    if v > 80:                    # ③ 판단
        over += 1
        found = True

print("평균:", total / len(values), "초과:", over, "이상:", found)   # ④ 출력
# → 평균: 79.0 초과: 2 이상: True


