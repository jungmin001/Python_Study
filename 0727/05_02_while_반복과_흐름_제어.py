print("========== 4. break ― 반복 즉시 종료 ==========")

# break 를 만나면 반복 '전체'를 그 자리에서 끝내고 바깥으로 나간다
for i in range(1, 11):            # 원래는 1~10
    if i == 5:
        break                     # 5를 만나면 즉시 종료 (5는 출력 안 됨!)
    print(i)                      # → 1 2 3 4
print("반복 종료")                 # → 반복 종료


print()
print("========== 5. continue ― 이번 회차만 건너뛰기 ==========")

# continue 를 만나면 그 아래 코드를 건너뛰고 '다음 회차'로 넘어간다
for i in range(1, 7):             # 1~6
    if i % 2 == 0:                # 짝수면
        continue                  # 이번 회차 건너뜀
    print(i)                      # → 1 3 5   (홀수만)


print()
print("========== 6. break vs continue ==========")

# ---------------------------------------------------------------------------
#   구분        break              continue
#   하는 일     반복 '전체' 종료     '이번 회차'만 건너뜀
#   이후 흐름   바깥으로 나감        다음 회차로 계속
#   쓰는 목적   찾았으니 그만        거르고 계속
# ---------------------------------------------------------------------------

# 같은 조건, 다른 결과 비교
for i in range(1, 6):
    if i == 3:
        break
    print(i)                      # → 1 2          (3에서 전체 중단)

print("-" * 10)

for i in range(1, 6):
    if i == 3:
        continue
    print(i)                      # → 1 2 4 5      (3만 건너뜀)


print()
print("========== 7. while True + break ==========")

# ---------------------------------------------------------------------------
# while True: 는 "일단 계속 반복" — 안에서 break 로 빠져나올 조건을 건다.
# 종료 시점을 반복 '안'에서 정하고 싶을 때 쓰는 패턴.
# ---------------------------------------------------------------------------

# 합이 100을 넘는 순간이 언제인지 찾기 (몇 번 돌지 미리 모른다!)
total = 0
i = 0
while True:
    i += 1
    total += i
    if total > 100:               # 목표를 넘으면
        break                     # 그 즉시 종료
print(i, "까지 합:", total)        # → 14 까지 합: 105

