print("========== 1. 왜 ― 담아만 두면 끝이 아니다 ==========")

# ---------------------------------------------------------------------------
# 리스트는 값을 담아 두는 것으로 끝이 아니라, 하나씩 꺼내 '처리'해야 의미가 있다.
# 값 100개를 인덱스로 출력하려면 print 를 100줄 써야 한다.
# → 같은 동작의 반복은 반복문에게 맡긴다.
# ---------------------------------------------------------------------------


print("========== 2. for 로 리스트 값 하나씩 꺼내기 ==========")

# ---------------------------------------------------------------------------
# 형식:  for 변수 in 리스트:
#            처리할 코드
#
# range 없이도 리스트의 '값'이 순서대로 하나씩 변수에 담긴다.
# ---------------------------------------------------------------------------

temps = [25, 32, 28]
for t in temps:                   # t 에 25 → 32 → 28 이 차례로 담김
    print("측정값:", t)
# → 측정값: 25
# → 측정값: 32
# → 측정값: 28

# 값의 개수만큼 자동으로 돈다. len 을 세거나 인덱스를 셀 필요가 없다!


print()
print("========== 3. for + if ― 조건에 맞는 값만 처리 ==========")

temps = [25, 32, 28, 35, 27]
for t in temps:
    if t > 30:                    # 각 값을 검사해서
        print(t, "고온 주의")      # 조건이 참인 값만 처리
# → 32 고온 주의
# → 35 고온 주의

# if / elif 로 여러 갈래 분류도 가능
temps = [25, 32, 28, 35, 19]
for t in temps:
    if t >= 30:
        print(t, "고온")
    elif t < 20:
        print(t, "저온")
# → 32 고온
# → 35 고온
# → 19 저온
#   (25, 28은 어느 조건에도 안 걸려 출력 없음)


print()
print("========== 4. 들여쓰기 단계 = 실행 빈도 ==========")

# ---------------------------------------------------------------------------
#   0단계 (반복 밖)   : 한 번만 실행
#   1단계 (for 안)    : 매 바퀴 실행
#   2단계 (if 안)     : 조건이 참인 바퀴에만 실행
# ---------------------------------------------------------------------------

temps = [25, 32, 28]
for t in temps:
    print("검사 중:", t)           # 1단계 → 매 바퀴 (3번)
    if t > 30:
        print("  고온!", t)        # 2단계 → 참일 때만 (1번)
print("검사 끝")                   # 0단계 → 반복 후 1번
# → 검사 중: 25
# → 검사 중: 32
# →   고온! 32
# → 검사 중: 28
# → 검사 끝


print()
print("========== 5. and 로 범위 필터링 ==========")

hours = [3, 8, 12, 6, 10, 4, 9]
for h in hours:
    if h >= 5 and h <= 10:        # 5 이상이면서 10 이하 (경계값 포함!)
        print(h)
# → 8 6 10 9   (한 줄씩)
#   경계값 확인: 정확히 10은 포함 (이하), 12는 제외


print()
print("========== 6. 최댓값·최솟값 ― 갱신 패턴 복습 ==========")

temps = [25, 32, 28, 35, 27]
biggest = temps[0]                # 첫 값(25)에서 시작
for t in temps:
    if t > biggest:
        biggest = t               # 더 크면 갱신:  25 → 32 → 35
print(biggest)                    # → 35


print()
print("========== 7. 조건에 맞는 값만 골라 부분 평균 ==========")

# 전체 평균이 아니라 '고온인 값들만'의 평균 — 합계와 개수를 조건 안에서만 누적
temps = [25, 32, 28, 36, 27, 31, 24]
total = 0
count = 0
for t in temps:
    if t > 30:                    # 30 초과만
        total += t                # 32 + 36 + 31 = 99
        count += 1                # 3개
print("고온 평균:", total / count)  # → 고온 평균: 33.0

# ★주의★ 나눌 때는 len(temps)가 아니라 count! (전체 7개가 아니라 조건에 맞은 3개)


print()
print("========== 8. 빈 리스트 + append ― 값을 가공해 새 리스트 ==========")

# ---------------------------------------------------------------------------
# 패턴: ① 빈 리스트를 반복 '밖'에서 준비  ② for 로 돌며  ③ append 로 담기
# (누적 변수 total = 0 과 똑같은 구조 — 그릇만 리스트로 바뀐 것!)
# ---------------------------------------------------------------------------

temps = [25, 26, 24, 28]
doubled = []                      # ① 빈 그릇
for t in temps:                   # ②
    doubled.append(t * 2)         # ③ 가공한 값을 담기
print(doubled)                    # → [50, 52, 48, 56]

# 섭씨 → 화씨 변환 (가공 공식만 바꾸면 무엇이든)
temps = [25, 26, 24, 28, 27]
fahrenheit = []
for t in temps:
    fahrenheit.append(t * 1.8 + 32)
print(fahrenheit)                 # → [77.0, 78.80000000000001, 75.2, 82.4, 80.6]
#   78.8 이 아니라 78.800...01 — 실수 계산의 작은 오차(02_02)가 리스트 안에서도 보인다.
#   보기 좋게 담으려면 round 를 함께 쓴다:
fahrenheit2 = []
for t in temps:
    fahrenheit2.append(round(t * 1.8 + 32, 1))
print(fahrenheit2)                # → [77.0, 78.8, 75.2, 82.4, 80.6]


print()
print("========== 9. for + if + append ― 필터링으로 새 리스트 ==========")

# 조건에 맞는 값만 골라 담으면 '필터링'이 된다
temps = [25, 32, 28, 35, 27]
high = []
for t in temps:
    if t > 30:
        high.append(t)            # 30 초과만 담기
print(high)                       # → [32, 35]

temps = [25, 32, 28, 35, 27, 31, 24, 33]
hot = []
for t in temps:
    if t > 30:
        hot.append(t)
print(hot)                        # → [32, 35, 31, 33]
print(len(hot))                   # → 4    (몇 개 걸러졌나)


print()
print("========== 10. 데이터 처리 4단계 패턴 정리 ==========")

# ---------------------------------------------------------------------------
# 반복으로 하는 일은 결국 네 가지 패턴이다:
#
#   ① 출력       for 로 print                     값 확인
#   ② 조건       for + if 로 선별                  필터링 출력
#   ③ 계산       0에서 시작해 합계·개수·평균         누적 변수
#   ④ 새 리스트   빈 리스트에 append                가공·필터링 저장
#
# 공통 구조: 그릇은 반복 '밖'에서 준비 → for → (if) → 담기/누적
# ---------------------------------------------------------------------------


print("========== 11. 리스트 안의 리스트 (맛보기) ==========")

# 리스트는 값으로 리스트도 담을 수 있다. 대괄호 두 번으로 안쪽 값에 접근.
sensors = [[25, 26], [30, 31]]    # 센서 2대의 측정값 묶음
print(sensors[0])                 # → [25, 26]   (첫 번째 묶음)
print(sensors[0][1])              # → 26         (첫 묶음의 두 번째 값)
print(sensors[1][0])              # → 30         (둘째 묶음의 첫 값)


print()
print("========== 12. 종합 : 센서 데이터 분석 ==========")

# 반복·조건·계산·새 리스트를 하나의 분석 흐름으로
temps = [25, 32, 28, 35, 27, 31, 24, 33, 29, 36]

# ① 전체 평균
total = 0
for t in temps:
    total += t
print("전체 평균:", total / len(temps))    # → 전체 평균: 30.0

# ② 30 초과 값만 새 리스트로
hot = []
for t in temps:
    if t > 30:
        hot.append(t)
print("고온 개수:", len(hot))               # → 고온 개수: 5   ([32,35,31,33,36])

# ③ 고온 값들의 평균
hot_total = 0
for h in hot:
    hot_total += h
print("고온 평균:", hot_total / len(hot))   # → 고온 평균: 33.4

# 전체 평균(30.0)과 고온 평균(33.4)을 비교하면 상태를 판단할 수 있다


