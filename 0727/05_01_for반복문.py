#  사용법  : "→" 결과를 먼저 예상한 뒤 실행해서 맞춰보기
# =============================================================================

print("========== 1. 왜 반복문인가 ==========")

# ---------------------------------------------------------------------------
# 같은 코드를 여러 번 복사해 붙이는 대신, "이 코드를 N번 실행하라"를 한 번만 지시.
# 데이터 수백·수천 개 처리의 바탕이 되는 도구다.
#
# 형식:
#     for 반복변수 in range(횟수):
#         반복할 코드              ← 들여쓰기 = 반복되는 블록 (조건문과 같은 규칙!)
# ---------------------------------------------------------------------------

for i in range(3):
    print("안녕하세요")            # → 안녕하세요  (3번 출력)


print()
print("========== 2. range ― 반복 횟수와 숫자 흐름 ==========")

# ---------------------------------------------------------------------------
#   range(끝)              0부터 끝-1까지        range(5)      → 0,1,2,3,4
#   range(시작, 끝)         시작부터 끝-1까지      range(1,6)    → 1,2,3,4,5
#   range(시작, 끝, 증가)    증가값만큼 건너뛰며     range(0,10,2) → 0,2,4,6,8
#
#   ★ 끝 숫자는 포함되지 않는다! (슬라이싱의 '끝 제외'와 같은 규칙)
# ---------------------------------------------------------------------------

for i in range(5):
    print(i)                      # → 0 1 2 3 4  (5는 없다!)

print("-" * 10)

for i in range(1, 6):
    print(i)                      # → 1 2 3 4 5

print("-" * 10)

for i in range(0, 10, 2):
    print(i)                      # → 0 2 4 6 8

print("-" * 10)

# 증가값이 음수면 역순
for i in range(5, 0, -1):
    print(i)                      # → 5 4 3 2 1

# 방향이 안 맞으면 오류 없이 '한 번도 실행 안 됨' (빈 반복)
for i in range(5, 0):             # 5에서 0으로 커질 수 없음
    print("이 줄은 출력되지 않는다")


print()
print("========== 3. 반복 변수 값의 변화 추적 ==========")

# 반복 변수 i 는 회차마다 다음 값으로 바뀐다
for i in range(3):
    print("현재 i:", i)            # → 현재 i: 0 / 현재 i: 1 / 현재 i: 2


print()
print("========== 4. 들여쓰기와 실행 범위 ==========")

# 조건문과 완전히 같은 규칙: 들여쓰기 안 = 반복됨, 밖 = 반복 끝난 뒤 한 번
for i in range(3):
    print("반복")                  # → 반복 반복 반복  (3번)
print("끝")                       # → 끝             (1번)


print()
print("========== 5. ★핵심 패턴★ 누적 변수로 합계 구하기 ==========")

# ---------------------------------------------------------------------------
# 누적 변수 패턴 3단계:
#   ① 반복 '밖'에서 0으로 시작        total = 0
#   ② 반복 안에서 계속 더하기         total += i
#   ③ 반복이 끝난 뒤 결과 사용        print(total)
# ---------------------------------------------------------------------------

total = 0                         # ① 반복 밖에서 한 번만!
for i in range(1, 6):             # i = 1,2,3,4,5
    total += i                    # ② total = total + i
print("최종 합계:", total)         # → 최종 합계: 15

# 회차별 추적:  시작 0 → 1회차 0+1=1 → 2회차 1+2=3 → 3 +3=6 → +4=10 → +5=15

# ★함정★ 초기화를 반복 '안'에 넣으면?
wrong = 0
for i in range(1, 4):
    wrong = 0                     # 매 바퀴 0으로 되돌아감!
    wrong += i
print(wrong)                      # → 3   (마지막 i만 남는다. 6이 아니다!)

right = 0                         # 올바른 위치: 반복 밖
for i in range(1, 4):
    right += i
print(right)                      # → 6   (1+2+3)


print()
print("========== 6. 개수 세기 패턴 (for + if) ==========")

count = 0
for i in range(1, 11):            # 1~10
    if i > 5:                     # 5보다 큰 값만
        count += 1                # 만족할 때만 1 증가
print("개수:", count)              # → 개수: 5   (6,7,8,9,10)


print()
print("========== 7. 평균 구하기 패턴 ==========")

total = 0
count = 0
for i in range(1, 6):             # 1~5
    total += i
    count += 1
print("평균:", total / count)      # → 평균: 3.0   (15 / 5)


print()
print("========== 8. 반복 변수 활용하기 ==========")

# i 를 계산에 쓰기
for i in range(1, 4):
    print(i, "의 제곱은", i * i)    # → 1 의 제곱은 1 / 2 의 제곱은 4 / 3 의 제곱은 9

# 0부터 시작하는 i 를 1번부터로 보이게
for i in range(3):
    print(i + 1, "번 항목")        # → 1 번 항목 / 2 번 항목 / 3 번 항목

# 문자열 누적 (숫자 대신 글자를 이어 붙이기)
line = ""                         # 빈 글자로 시작
for i in range(5):
    line += "*"
print(line)                       # → *****

# 배수표 만들기
for i in range(1, 6):
    print("3 x", i, "=", 3 * i)   # → 3 x 1 = 3  ...  3 x 5 = 15


print()
print("========== 9. 중첩 반복 ― 반복 안의 반복 ==========")

# ---------------------------------------------------------------------------
# 바깥 반복 1바퀴마다 안쪽 반복이 '전부' 돈다.
# 전체 실행 횟수 = 바깥 횟수 x 안쪽 횟수   (2x3=6, 9x9=81, 100x100=10000)
# ---------------------------------------------------------------------------

for dan in range(2, 4):           # 바깥: 2단, 3단
    for su in range(1, 4):        # 안쪽: 1,2,3
        print(dan, "x", su, "=", dan * su)
    print("---")                  # 한 단 끝날 때마다 (바깥 블록)
# → 2 x 1 = 2
# → 2 x 2 = 4
# → 2 x 3 = 6
# → ---
# → 3 x 1 = 3
# → 3 x 2 = 6
# → 3 x 3 = 9
# → ---

# 구구단 전체는 range(2, 10) 과 range(1, 10) 으로 확장하면 된다


print()
print("========== 10. 반복 횟수를 입력으로 정하기 ==========")

# 실제 입력 버전 (주석을 풀면 동작):
# n = int(input("몇 번 반복할까요? "))

n = int("3")                      # ← input 흉내
for i in range(n):
    print("반복 중...")            # → 반복 중... (3번)

# 실습: 1부터 N까지 합
# n = int(input("N을 입력하세요: "))
n = int("10")                     # ← input 흉내
total = 0
for i in range(1, n + 1):         # 1부터 N'까지' 포함하려면 끝은 n+1
    total += i
print("합:", total)                # → 합: 55


